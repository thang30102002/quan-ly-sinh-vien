-- CSDL: PostgreSQL 16 (chạy bằng Docker, xem docs/docker.md).
-- Docker tự chạy file này rồi đến seed.sql khi tạo database lần đầu.
-- Chạy tay (xóa các bảng cũ nếu có rồi tạo lại từ đầu):
--   docker compose exec -T db psql -U qlsv -d qlsv -v ON_ERROR_STOP=1 < database/schema.sql
--
-- Quy tắc nghiệp vụ (BR-xx) xem docs/yeu-cau.md, sơ đồ xem docs/erd.md.
--
-- Các quy tắc KHÔNG biểu diễn được bằng ràng buộc CSDL, kiểm tra ở Service:
--   BR-04 tối đa 12 tín chỉ/học kỳ, BR-05 không trùng môn trong học kỳ,
--   BR-07 chỉ SV "Đang học" được đăng ký, BR-14/15 không xóa/hủy khi có điểm,
--   BR-17 email, tuổi >= 16, BR-21 các buổi của một lớp không trùng nhau,
--   BR-22/23 trùng lịch học, BR-24 tiền tố mã lớp = mã học phần,
--   BR-25 lớp đủ sĩ số.
-- =====================================================================

SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS enrollments, schedules, class_sections, semesters, courses, students CASCADE;

-- ---------------------------------------------------------------------
-- Sinh viên
-- ---------------------------------------------------------------------
CREATE TABLE students (
    id            INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    student_code  VARCHAR(9)   NOT NULL,              -- Mã SV, vd SV2026001 (BR-01)
    full_name     VARCHAR(100) NOT NULL,              -- Họ tên (BR-17)
    dob           DATE         NOT NULL,              -- Ngày sinh
    -- Lưu mã tiếng Anh bằng VARCHAR + CHECK (không dùng kiểu ENUM của
    -- PostgreSQL) để JDBC gán được bằng setString
    gender        VARCHAR(6)   NOT NULL,
    email         VARCHAR(100)     NULL,
    phone         VARCHAR(10)      NULL,              -- 10 chữ số, bắt đầu bằng 0 (BR-17)
    class_name    VARCHAR(20)  NOT NULL,              -- Lớp sinh hoạt, vd CNTT-K24A
    intake_year   SMALLINT     NOT NULL,              -- Khóa (năm nhập học)
    status        VARCHAR(9)   NOT NULL DEFAULT 'STUDYING',
    PRIMARY KEY (id),
    CONSTRAINT uq_students_code UNIQUE (student_code),
    -- BR-01: toán tử ~ phân biệt hoa thường
    CONSTRAINT chk_students_code CHECK (student_code ~ '^SV[0-9]{7}$'),
    -- BR-01: 4 số sau "SV" là năm nhập học (so sánh chuỗi để mã sai không làm lỗi ép kiểu)
    CONSTRAINT chk_students_intake_year
        CHECK (intake_year BETWEEN 2000 AND 2100
               AND SUBSTRING(student_code FROM 3 FOR 4) = CAST(intake_year AS TEXT)),
    CONSTRAINT chk_students_full_name CHECK (CHAR_LENGTH(TRIM(full_name)) > 0),
    CONSTRAINT chk_students_phone CHECK (phone ~ '^0[0-9]{9}$'),
    CONSTRAINT chk_students_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    -- BR-20: Đang học / Bảo lưu / Thôi học / Tốt nghiệp
    CONSTRAINT chk_students_status
        CHECK (status IN ('STUDYING', 'RESERVED', 'DROPPED', 'GRADUATED'))
);

-- ---------------------------------------------------------------------
-- Học phần
-- ---------------------------------------------------------------------
CREATE TABLE courses (
    id           INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    course_code  VARCHAR(7)   NOT NULL,               -- Mã học phần, vd IT101 (BR-02)
    name         VARCHAR(150) NOT NULL,               -- Tên học phần
    credits      SMALLINT     NOT NULL,               -- Số tín chỉ 1–6 (BR-18)
    description  TEXT             NULL,               -- Mô tả
    PRIMARY KEY (id),
    CONSTRAINT uq_courses_code UNIQUE (course_code),
    CONSTRAINT chk_courses_code CHECK (course_code ~ '^[A-Z]{2,4}[0-9]{3}$'),
    CONSTRAINT chk_courses_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT chk_courses_credits CHECK (credits BETWEEN 1 AND 6)
);

-- ---------------------------------------------------------------------
-- Học kỳ
-- ---------------------------------------------------------------------
CREATE TABLE semesters (
    id             INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    semester_code  VARCHAR(6)   NOT NULL,             -- Mã học kỳ, vd 2026-1 (BR-03)
    name           VARCHAR(100) NOT NULL,             -- Tên học kỳ
    start_date     DATE         NOT NULL,
    end_date       DATE         NOT NULL,
    is_open        BOOLEAN      NOT NULL DEFAULT FALSE, -- Đang mở đăng ký (BR-26)
    PRIMARY KEY (id),
    CONSTRAINT uq_semesters_code UNIQUE (semester_code),
    CONSTRAINT chk_semesters_code CHECK (semester_code ~ '^[0-9]{4}-[123]$'),
    CONSTRAINT chk_semesters_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    -- BR-19
    CONSTRAINT chk_semesters_dates CHECK (end_date > start_date)
);

-- BR-26: chỉ một học kỳ mở đăng ký (UNIQUE chỉ áp cho các dòng is_open = TRUE)
CREATE UNIQUE INDEX uq_semesters_open ON semesters (is_open) WHERE is_open;

-- ---------------------------------------------------------------------
-- Lớp học phần: một học phần mở trong một học kỳ, có thể nhiều lớp
-- ---------------------------------------------------------------------
CREATE TABLE class_sections (
    id             INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    section_code   VARCHAR(10)  NOT NULL,             -- Mã lớp, vd IT101-01 (BR-24)
    course_id      INTEGER      NOT NULL,
    semester_id    INTEGER      NOT NULL,
    lecturer_name  VARCHAR(100)     NULL,             -- Giảng viên phụ trách
    max_students   SMALLINT     NOT NULL,             -- Sĩ số tối đa (BR-25)
    PRIMARY KEY (id),
    -- BR-24: mã lớp duy nhất trong một học kỳ
    CONSTRAINT uq_class_sections_code UNIQUE (semester_id, section_code),
    -- BR-16: không xóa học phần / học kỳ đã mở lớp
    CONSTRAINT fk_class_sections_course
        FOREIGN KEY (course_id) REFERENCES courses (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_class_sections_semester
        FOREIGN KEY (semester_id) REFERENCES semesters (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_class_sections_code
        CHECK (section_code ~ '^[A-Z]{2,4}[0-9]{3}-[0-9]{2}$'),
    CONSTRAINT chk_class_sections_max CHECK (max_students > 0)
);

-- ---------------------------------------------------------------------
-- Thời khóa biểu: các buổi học lặp lại hằng tuần của lớp học phần
-- ---------------------------------------------------------------------
CREATE TABLE schedules (
    id            INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    section_id    INTEGER     NOT NULL,
    day_of_week   SMALLINT    NOT NULL,               -- 2 = Thứ 2 … 7 = Thứ 7, 8 = Chủ nhật
    start_period  SMALLINT    NOT NULL,               -- Tiết bắt đầu 1–12
    end_period    SMALLINT    NOT NULL,               -- Tiết kết thúc 1–12
    room          VARCHAR(20)     NULL,               -- Phòng học
    PRIMARY KEY (id),
    -- Chặn nhập trùng y hệt; trùng khoảng tiết (BR-21) kiểm tra ở Service
    CONSTRAINT uq_schedules_slot UNIQUE (section_id, day_of_week, start_period),
    -- Xóa lớp học phần thì xóa luôn các buổi học
    CONSTRAINT fk_schedules_section
        FOREIGN KEY (section_id) REFERENCES class_sections (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    -- BR-21
    CONSTRAINT chk_schedules_day CHECK (day_of_week BETWEEN 2 AND 8),
    CONSTRAINT chk_schedules_periods
        CHECK (start_period BETWEEN 1 AND 12
               AND end_period BETWEEN 1 AND 12
               AND start_period <= end_period)
);

-- ---------------------------------------------------------------------
-- Đăng ký học phần và điểm
-- total / letter / gpa4 do phần mềm tính (GpaCalculator, #13) rồi lưu lại;
-- các CHECK bên dưới bảo đảm giá trị lưu khớp BR-09, BR-10.
-- ---------------------------------------------------------------------
CREATE TABLE enrollments (
    id             INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    student_id     INTEGER      NOT NULL,
    section_id     INTEGER      NOT NULL,
    registered_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attendance     NUMERIC(3,1)     NULL,             -- Chuyên cần 0–10 (BR-08)
    midterm        NUMERIC(3,1)     NULL,             -- Giữa kỳ 0–10 (BR-08)
    final_exam     NUMERIC(3,1)     NULL,             -- Cuối kỳ 0–10 (BR-08)
    total          NUMERIC(3,1)     NULL,             -- Điểm tổng kết (BR-09)
    letter         VARCHAR(2)       NULL,             -- Điểm chữ (BR-10)
    gpa4           NUMERIC(2,1)     NULL,             -- Điểm hệ 4 (BR-10)
    PRIMARY KEY (id),
    CONSTRAINT uq_enrollments UNIQUE (student_id, section_id),
    -- BR-14: xóa sinh viên (chưa có điểm) thì xóa luôn đăng ký
    CONSTRAINT fk_enrollments_student
        FOREIGN KEY (student_id) REFERENCES students (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    -- BR-16: không xóa lớp học phần đã có sinh viên đăng ký
    CONSTRAINT fk_enrollments_section
        FOREIGN KEY (section_id) REFERENCES class_sections (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- BR-08
    CONSTRAINT chk_enrollments_attendance CHECK (attendance BETWEEN 0 AND 10),
    CONSTRAINT chk_enrollments_midterm    CHECK (midterm    BETWEEN 0 AND 10),
    CONSTRAINT chk_enrollments_final      CHECK (final_exam BETWEEN 0 AND 10),
    -- BR-09: chỉ có điểm tổng kết khi đủ 3 điểm thành phần, và phải đúng công thức.
    -- ROUND của NUMERIC làm tròn nửa lên (8.45 → 8.5), khớp RoundingMode.HALF_UP.
    CONSTRAINT chk_enrollments_total
        CHECK (total IS NULL
               OR (attendance IS NOT NULL AND midterm IS NOT NULL AND final_exam IS NOT NULL
                   AND total = ROUND(attendance * 0.1 + midterm * 0.3 + final_exam * 0.6, 1))),
    -- BR-10: điểm chữ và hệ 4 đi cùng điểm tổng kết, đúng bảng quy đổi.
    -- Dùng IS NOT DISTINCT FROM vì CHECK chỉ chặn khi kết quả FALSE, so sánh
    -- với NULL bằng "=" cho UNKNOWN và sẽ lọt.
    CONSTRAINT chk_enrollments_letter
        CHECK ((total IS NULL AND letter IS NULL)
               OR total IS NOT NULL AND letter IS NOT DISTINCT FROM CASE
                               WHEN total >= 8.5 THEN 'A'
                               WHEN total >= 8.0 THEN 'B+'
                               WHEN total >= 7.0 THEN 'B'
                               WHEN total >= 6.5 THEN 'C+'
                               WHEN total >= 5.5 THEN 'C'
                               WHEN total >= 5.0 THEN 'D+'
                               WHEN total >= 4.0 THEN 'D'
                               ELSE 'F'
                           END),
    CONSTRAINT chk_enrollments_gpa4
        CHECK ((total IS NULL AND gpa4 IS NULL)
               OR total IS NOT NULL AND gpa4 IS NOT DISTINCT FROM CASE
                             WHEN total >= 8.5 THEN 4.0
                             WHEN total >= 8.0 THEN 3.5
                             WHEN total >= 7.0 THEN 3.0
                             WHEN total >= 6.5 THEN 2.5
                             WHEN total >= 5.5 THEN 2.0
                             WHEN total >= 5.0 THEN 1.5
                             WHEN total >= 4.0 THEN 1.0
                             ELSE 0.0
                         END)
);

COMMENT ON TABLE students       IS 'Sinh viên';
COMMENT ON TABLE courses        IS 'Học phần';
COMMENT ON TABLE semesters      IS 'Học kỳ';
COMMENT ON TABLE class_sections IS 'Lớp học phần';
COMMENT ON TABLE schedules      IS 'Thời khóa biểu lớp học phần';
COMMENT ON TABLE enrollments    IS 'Đăng ký lớp học phần và điểm';
